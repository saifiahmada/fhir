CREATE DATABASE IF NOT EXISTS db_rumah_sakit CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE db_rumah_sakit;

CREATE TABLE IF NOT EXISTS fhir_resources (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resource_type VARCHAR(40) NOT NULL,
  resource_id VARCHAR(100) NOT NULL,
  resource_json LONGTEXT NOT NULL,
  received_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_resource (resource_type, resource_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS received_bundles (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  bundle_identifier VARCHAR(100) NULL,
  sender VARCHAR(120) NULL,
  bundle_json LONGTEXT NOT NULL,
  received_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS api_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  outcome VARCHAR(30) NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
